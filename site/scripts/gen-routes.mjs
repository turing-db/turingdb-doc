// docs.json -> generated route table, nav tree and search index.
// Only pages referenced by docs.json become routes; the 3 orphan .mdx files on disk
// (benchmarks/benchmarks, tutorials/create_graph, snippets/snippet-intro) are excluded.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const contentRoot = path.resolve(root, '..');
const docsJson = JSON.parse(fs.readFileSync(path.join(contentRoot, 'docs.json'), 'utf8'));

const groups = [];
for (const tab of docsJson.navigation.tabs) {
  for (const g of tab.groups) {
    groups.push({ tab: tab.tab, group: g.group, pages: g.pages });
  }
}

const readFrontmatter = (slug) => {
  const file = path.join(contentRoot, `${slug}.mdx`);
  if (!fs.existsSync(file)) throw new Error(`missing content file for "${slug}"`);
  const src = fs.readFileSync(file, 'utf8');
  const m = src.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  const fm = {};
  if (m) {
    for (const line of m[1].split(/\r?\n/)) {
      const kv = line.match(/^([A-Za-z_]+):\s*(.*)$/);
      if (kv) fm[kv[1]] = kv[2].trim().replace(/^["']|["']$/g, '');
    }
  }
  return { fm, src };
};

const pages = [];
for (const g of groups) {
  for (const slug of g.pages) {
    const { fm, src } = readFrontmatter(slug);
    pages.push({
      slug,
      route: slug === 'index' ? '/' : `/${slug}`,
      group: g.group,
      tab: g.tab,
      title: fm.title ?? slug,
      sidebarTitle: fm.sidebarTitle ?? fm.title ?? slug,
      description: fm.description ?? '',
      body: src,
    });
  }
}

// ---------- routes + nav ----------
const routesTs = `// GENERATED by scripts/gen-routes.mjs — do not edit.
import type { ComponentType } from "react";

export type TocEntry = { depth: number; id: string; title: string };
export type PageModule = {
  default: ComponentType<Record<string, unknown>>;
  frontmatter?: { title?: string; sidebarTitle?: string; description?: string };
  tableOfContents?: TocEntry[];
};
export type DocPage = {
  slug: string;
  route: string;
  group: string;
  tab: string;
  title: string;
  sidebarTitle: string;
  description: string;
  load: () => Promise<PageModule>;
};

export const pages: DocPage[] = [
${pages
  .map(
    (p) => `  {
    slug: ${JSON.stringify(p.slug)},
    route: ${JSON.stringify(p.route)},
    group: ${JSON.stringify(p.group)},
    tab: ${JSON.stringify(p.tab)},
    title: ${JSON.stringify(p.title)},
    sidebarTitle: ${JSON.stringify(p.sidebarTitle)},
    description: ${JSON.stringify(p.description)},
    load: () => import(${JSON.stringify(`@content/${p.slug}.mdx`)}) as Promise<PageModule>,
  },`
  )
  .join('\n')}
];

export type NavGroup = { group: string; pages: DocPage[] };
export const navGroups: NavGroup[] = [
${groups
  .map(
    (g) => `  { group: ${JSON.stringify(g.group)}, pages: [${g.pages
      .map((s) => `pages[${pages.findIndex((p) => p.slug === s)}]`)
      .join(', ')}] },`
  )
  .join('\n')}
];

export const tabs: string[] = ${JSON.stringify([...new Set(groups.map((g) => g.tab))])};
export const byRoute = new Map(pages.map((p) => [p.route, p]));
`;

fs.writeFileSync(path.join(root, 'src/routes.generated.ts'), routesTs);

// ---------- search index ----------
const stripMdx = (src) =>
  src
    .replace(/^---[\s\S]*?---/, '')
    .replace(/```[\s\S]*?```/g, ' ')
    .replace(/<[^>]+>/g, ' ')
    .replace(/[*_`>#|]/g, ' ')
    .replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')
    .replace(/\s+/g, ' ')
    .trim();

const index = pages.map((p, i) => ({
  id: i,
  route: p.route,
  title: p.title,
  group: p.group,
  description: p.description,
  headings: [...p.body.matchAll(/^#{2,3}\s+(.+)$/gm)].map((m) => m[1].trim()).join(' · '),
  text: stripMdx(p.body).slice(0, 8000),
}));
fs.writeFileSync(path.join(root, 'src/search-index.generated.json'), JSON.stringify(index));

console.log(
  `[gen-routes] ${pages.length} routes, ${groups.length} groups, search index ${(
    JSON.stringify(index).length / 1024
  ).toFixed(0)} kB`
);
