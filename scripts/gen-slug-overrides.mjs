// Generates src/lib/slug-overrides.generated.ts from the captured live-site anchors.
// Only headings the base rule gets wrong are emitted, so the table stays small and
// self-documenting. Re-run after any change to slugify.ts.
import fs from 'node:fs';
import path from 'node:path';

const REF = process.env.REF ||
  '/tmp/claude-1001/-home-ubuntu-doc/2c93b371-c73f-4152-a81d-392a543bb2ad/scratchpad/ref2/styles';
const OUT = new URL('../src/lib/slug-overrides.generated.ts', import.meta.url);

const KEPT = /[\p{L}\p{N}_→←=&+/|—–’“”]/u;
const PICTO = /[\u{1F000}-\u{1FAFF}\u{2600}-\u{27BF}\u{2B00}-\u{2BFF}\u{FE00}-\u{FE0F}\u{1F1E6}-\u{1F1FF}]/u;
const SILENT = /[)\]["'`]/;

function base(input) {
  const s = input.replace(/​/g, '').replace(/ /g, ' ').trim().toLowerCase();
  let out = '', i = 0;
  while (i < s.length) {
    const ch = s[i];
    if (KEPT.test(ch)) { out += ch; i++; continue; }
    if (PICTO.test(ch)) { i++; continue; }
    let run = '';
    while (i < s.length && !KEPT.test(s[i])) {
      if (!PICTO.test(s[i]) && !SILENT.test(s[i])) run += s[i];
      i++;
    }
    if (i >= s.length) continue;
    if (!run.length) continue;
    out += run.length >= 3 ? '--' : '-';
  }
  return out;
}

if (!fs.existsSync(REF)) {
  console.warn(`[gen-slug-overrides] reference dir absent (${REF}); keeping existing table`);
  process.exit(0);
}

const overrides = new Map();
let total = 0, matched = 0;
for (const f of fs.readdirSync(REF).filter(f => f.endsWith('.json'))) {
  const meta = JSON.parse(fs.readFileSync(path.join(REF, f), 'utf8')).__meta;
  if (!meta?.headings?.length) continue;
  const seen = new Map();
  for (const h of meta.headings) {
    if (!h.id || /^_r_/.test(h.id)) continue; // React useId on card titles — not real anchors
    const text = JSON.parse(h.x).replace(/​/g, '').replace(/ /g, ' ').trim();
    const b = base(text);
    const n = seen.get(b) ?? 0;
    seen.set(b, n + 1);
    const expectBase = n === 0 ? h.id : h.id.replace(/-\d+$/, '');
    total++;
    if (b === expectBase) matched++;
    else if (!overrides.has(text)) overrides.set(text, expectBase);
  }
}

const body = [...overrides.entries()]
  .sort((a, b) => a[0].localeCompare(b[0]))
  .map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`)
  .join('\n');

fs.writeFileSync(OUT, `// GENERATED by scripts/gen-slug-overrides.mjs — do not edit by hand.
// Headings whose slug the base rule in slugify.ts does not reproduce. Values are the ids
// the live Mintlify site emits, so anchors stay link-compatible.
// base rule matched ${matched}/${total} headings; ${overrides.size} overrides below.
export const SLUG_OVERRIDES: Record<string, string> = {
${body}
};
`);
console.log(`[gen-slug-overrides] base ${matched}/${total}, ${overrides.size} overrides -> ${path.basename(OUT.pathname)}`);
